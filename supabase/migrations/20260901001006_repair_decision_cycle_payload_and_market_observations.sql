-- Align production decisions with the current paper_cycle payload and create
-- an auditable store for the real INDODAX observations feeding the pulse.

ALTER TABLE public.decisions
  ADD COLUMN IF NOT EXISTS cycle_at timestamptz,
  ADD COLUMN IF NOT EXISTS trading_date date,
  ADD COLUMN IF NOT EXISTS pair text,
  ADD COLUMN IF NOT EXISTS price numeric,
  ADD COLUMN IF NOT EXISTS balance numeric,
  ADD COLUMN IF NOT EXISTS portfolio_value numeric,
  ADD COLUMN IF NOT EXISTS daily_pnl numeric,
  ADD COLUMN IF NOT EXISTS total_pnl numeric,
  ADD COLUMN IF NOT EXISTS active_positions integer,
  ADD COLUMN IF NOT EXISTS positions jsonb NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS bid numeric,
  ADD COLUMN IF NOT EXISTS ask numeric;

CREATE OR REPLACE FUNCTION public.sync_decision_symbol_from_pair()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF (NEW.symbol IS NULL OR btrim(NEW.symbol) = '') AND NEW.pair IS NOT NULL THEN
    NEW.symbol := NEW.pair;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_decisions_sync_symbol ON public.decisions;
CREATE TRIGGER trg_decisions_sync_symbol
BEFORE INSERT OR UPDATE ON public.decisions
FOR EACH ROW
EXECUTE FUNCTION public.sync_decision_symbol_from_pair();

CREATE INDEX IF NOT EXISTS idx_decisions_cycle_at
  ON public.decisions(symbol, cycle_at DESC);

CREATE TABLE IF NOT EXISTS public.market_observations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_id text,
  session_id text,
  symbol text NOT NULL,
  observed_at timestamptz NOT NULL DEFAULT now(),
  minute_bucket timestamptz NOT NULL,
  price numeric NOT NULL,
  source text NOT NULL,
  observation_type text NOT NULL,
  trade_count integer NOT NULL DEFAULT 0,
  move_from_previous_pct numeric,
  pulse_status text,
  raw_observation jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_market_observations_symbol_time
  ON public.market_observations(symbol, observed_at DESC);
CREATE INDEX IF NOT EXISTS idx_market_observations_minute
  ON public.market_observations(symbol, minute_bucket DESC);
CREATE INDEX IF NOT EXISTS idx_market_observations_cycle
  ON public.market_observations(cycle_id);

ALTER TABLE public.market_observations ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.market_observations IS
  'Audit trail of real INDODAX observations used by the paper trading market pulse; service-role writes only.';
